import { join } from 'node:path';
import { z } from 'zod';
import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { ok, err } from '../mcpResult.js';
import type { ProviderAdapter } from '../adapters/types.js';
import type { ReportKind } from '../domain/types.js';

/**
 * `report_download` — generate the same PDF reports the SimplifyQA UI offers, for a test case or a
 * suite execution, and save them to disk. The report content/format/masking come from the product's
 * report service; this tool only chooses the run, asks which report types, and writes the files.
 */
export type ReportToolsDeps = {
  getAdapter: () => ProviderAdapter | null;
};

const NOT_CONNECTED =
  'Not connected to a product. Use qa_connect first — reports are generated by the backend report service.';

function describeError(e: unknown): string {
  return e instanceof Error ? e.message : String(e);
}

const norm = (v: string) => v.trim().toLowerCase().replace(/[-\s]+/g, '_');

export function registerReportTools(server: McpServer, deps: ReportToolsDeps): void {
  server.registerTool(
    'report_download',
    {
      title: 'Download PDF reports for a test case or suite execution',
      description:
        'Generate and SAVE the PDF execution reports the SimplifyQA UI offers.\n' +
        '  • target "testcase" — report types: `detailed`, `summary` (pick one or both).\n' +
        '  • target "suite" — report types: `suite` (overall suite report), `detailed` (one detailed report ' +
        'per test case in the suite), `summary` (one summary report per test case). Pick one, several or all.\n' +
        '`ref` is the test case id/key (TC_123) or the suite NAME / id. If the user did NOT say which report ' +
        'type(s) they want, call WITHOUT `reportTypes` — the tool replies with the choices; ASK the user, then ' +
        'call again. If they named the type ("the summary pdf report"), pass it directly and do not ask. ' +
        'The report is for ONE execution: by default the most recent one, and the response states which ' +
        'execution was used and how many others exist — pass `runId` (execution id) to pick another. Files are ' +
        'saved under `outDir` (default ./qa-reports) and their paths returned. Protected parameters are masked ' +
        'by the report service. Requires a live connection; no agent needed.',
      inputSchema: {
        target: z.enum(['testcase', 'suite']).describe('Report for a test case or a suite.'),
        ref: z.string().min(1).describe('Test case id/key (TC_123), or suite name / id.'),
        reportTypes: z.array(z.enum(['detailed', 'summary', 'suite'])).optional().describe(
          'Which reports. Omit to get the choices and ASK the user. testcase: detailed | summary. suite: suite | detailed | summary.',
        ),
        runId: z.string().optional().describe('Execution id to report on. Omit to use the most recent execution.'),
        outDir: z.string().optional().describe('Folder to save PDFs into. Default: ./qa-reports'),
      },
      annotations: { readOnlyHint: false },
    },
    async ({ target, ref, reportTypes, runId, outDir }) => {
      const adapter = deps.getAdapter();
      if (!adapter) return err(NOT_CONNECTED);
      if (!adapter.downloadReports) return err('This product does not support downloading PDF reports.');
      try {
        // ---- which report types?
        const allowed: ReportKind[] = target === 'suite' ? ['suite', 'detailed', 'summary'] : ['detailed', 'summary'];
        if (!reportTypes || reportTypes.length === 0) {
          const choices = target === 'suite'
            ? '- `suite` — overall suite PDF report\n- `detailed` — a detailed report for EACH test case in the suite\n- `summary` — a summary report for EACH test case in the suite'
            : '- `detailed` — detailed report\n- `summary` — summary report\n- both';
          return ok(
            `Which report(s) do you want for this ${target}?\n${choices}\n\n**Ask the user** (one, several or all), then call \`report_download\` again with \`reportTypes\`.`,
            { needs: 'reportTypes', options: allowed },
          );
        }
        const bad = reportTypes.filter((k) => !allowed.includes(k));
        if (bad.length) {
          return err(`Report type(s) ${bad.map((b) => `"${b}"`).join(', ')} are not available for a ${target}. Choose from: ${allowed.join(', ')}.`);
        }
        const kinds = [...new Set(reportTypes)];

        // ---- which execution?
        let execId = runId;
        let how = '';
        if (!execId) {
          const entityId = await resolveEntityId(adapter, target, ref);
          if (typeof entityId !== 'string' || entityId.startsWith('\u0000')) {
            return err(typeof entityId === 'string' ? entityId.slice(1) : 'Could not resolve the target.');
          }
          if (!adapter.listRecentRuns) return err('This product cannot list executions — pass `runId` (execution id).');
          const runs = await adapter.listRecentRuns(target === 'suite' ? 'SUITE' : 'TC', entityId, 10);
          if (!runs.length) return err(`${ref} has never been executed — there is no execution to report on.`);
          const latest = runs[0]!;
          execId = latest.runId;
          how = runs.length > 1
            ? ` Used the most recent of ${runs.length}+ executions (EX-${latest.runId}${latest.endedAt ? `, ended ${latest.endedAt}` : ''}); pass \`runId\` to choose another: ${runs.slice(1, 5).map((r) => `EX-${r.runId}`).join(', ')}.`
            : ` Used its only execution (EX-${latest.runId}).`;
        } else {
          how = ` Used execution EX-${execId} as requested.`;
        }

        const dir = outDir ?? join(process.cwd(), 'qa-reports');
        const res = await adapter.downloadReports({ runId: execId, kinds, outDir: dir });
        if (!res.files.length) {
          return err(`No report files were produced for ${ref}.${res.notes.length ? '\n' + res.notes.join('\n') : ''}`);
        }
        const lines = res.files.map((f) => `- ${f.label} — \`${f.path}\` (${(f.bytes / 1024).toFixed(0)} KB)`).join('\n');
        return ok(
          `Generated ${res.files.length} PDF report${res.files.length === 1 ? '' : 's'} for ${res.scope} **${ref}** (${res.runLabel}).${how}\n\n${lines}` +
            (res.notes.length ? `\n\nNotes:\n${res.notes.map((n) => `- ${n}`).join('\n')}` : ''),
          { files: res.files, execution: execId, notes: res.notes },
        );
      } catch (e) {
        return err(`Report generation failed: ${describeError(e)}`);
      }
    },
  );
}

/** Resolve `ref` to the entity id (TC id / suite id). Returns a string, or '\u0000'+message on failure. */
async function resolveEntityId(adapter: ProviderAdapter, target: 'testcase' | 'suite', ref: string): Promise<string> {
  if (target === 'testcase') return ref.trim();
  if (/^\d+$/.test(ref.trim()) || /^(su|suite)[_-]\d+$/i.test(ref.trim())) return ref.trim();
  const suites = await adapter.listSuites();
  const want = norm(ref);
  const exact = suites.filter((s) => norm(s.name) === want || norm(s.id) === want);
  if (exact.length === 1) return exact[0]!.id;
  if (exact.length > 1) {
    return '\u0000' + `"${ref}" matches ${exact.length} suites — ambiguous. Ask the user which one:\n${exact.map((s) => `- ${s.name} (id ${s.id})`).join('\n')}`;
  }
  const near = suites.filter((s) => norm(s.name).includes(want)).slice(0, 10);
  return '\u0000' + `No suite named "${ref}" was found.${near.length ? `\n\nClosest matches:\n${near.map((s) => `- ${s.name} (id ${s.id})`).join('\n')}` : ''}`;
}
